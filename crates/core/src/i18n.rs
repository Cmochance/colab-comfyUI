/// Exports the full key-value lookup table for the Svelte frontend.
pub fn message_table(locale: Locale) -> BTreeMap<&'static str, &'static str> {
    MsgKey::all()
        .iter()
        .map(|&k| (k.as_str(), t(locale, k)))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_locales_cover_all_keys_with_non_empty_text() {
        for locale in [Locale::ZhHans, Locale::En] {
            let table = message_table(locale);
            assert_eq!(table.len(), MsgKey::all().len());
            for (k, v) in table {
                assert!(
                    !v.trim().is_empty(),
                    "empty translation for {k} in {locale:?}"
                );
            }
        }
    }
}
