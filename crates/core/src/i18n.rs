/// Supported UI locales (`zh-Hans` and `en`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Locale {
    #[default]
    #[serde(rename = "zh-Hans")]
    ZhHans,
    #[serde(rename = "en")]
    En,
}

/// Detects the default UI locale from injected POSIX locale values.
pub fn detect_locale_from_env(
    lc_all: Option<&str>,
    lc_messages: Option<&str>,
    lang: Option<&str>,
) -> Locale {
    for val in [lc_all, lc_messages, lang].into_iter().flatten() {
        let lower = val.trim().to_ascii_lowercase();
        if lower.starts_with("en") {
            return Locale::En;
        }
        if lower.starts_with("zh") {
            return Locale::ZhHans;
        }
    }
    Locale::ZhHans
}

